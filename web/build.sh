#!/usr/bin/env bash
# Build the browser bundle. The output is one ES module that defines the two globals
# the page expects, so the page can load it with a plain <script type="module">.
set -euo pipefail
cd "$(dirname "$0")/.."
export PATH="$HOME/.moon/bin:$PATH"
moon build --target js --release src/web
out=_build/js/release/build/src/web/web.js
if [ ! -f "$out" ]; then
  echo "build did not produce $out" >&2
  exit 1
fi
{
  echo "// Generated by web/build.sh from src/web — do not edit."
  sed 's/^import \* as .*$//' "$out"
} > web/moonprove.js
wc -c < web/moonprove.js | xargs echo "wrote web/moonprove.js bytes:"
